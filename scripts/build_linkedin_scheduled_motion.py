def fmt(value):
    if value>=10000:return f"${value/1000:,.0f}K" if value<1000000 else f"${value/1000000:,.1f}M"
    if value>=1:return f"{value:,.1f}".rstrip("0").rstrip(".")
    return f"{value:.4f}".rstrip("0").rstrip(".")


