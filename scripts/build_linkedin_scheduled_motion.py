def validate(items):
    checks=[]
    for p in items:
        dest=OUT/(p["id"].lower()+"-"+p["slug"])
        probe=json.loads(subprocess.check_output(["ffprobe","-v","error","-show_streams","-show_format","-of","json",str(dest/"motion.mp4")]))
        v=next(s for s in probe["streams"] if s["codec_type"]=="video")
        assert (v["width"],v["height"],v["codec_name"],v["pix_fmt"])==(W,H,"h264","yuv420p")
        assert abs(float(probe["format"]["duration"])-SECONDS)<.1
        assert int(v["nb_frames"])==FPS*SECONDS
        gif=Image.open(dest/"motion.gif")
        assert gif.n_frames>=300 and gif.info.get("loop")==0
        # Confirm actual GIF frames differ within each scene, not only at cuts.
        unique=[]
        for scene in range(6):
            hashes=set()
            for n in (8,20,35,48):
                gif.seek(scene*60+n)
                # Exclude the timeline/header: visible diagram motion must pass.
                hashes.add(hashlib.sha256(gif.convert("RGB").crop((35,270,685,780)).tobytes()).hexdigest())
            assert len(hashes)>=2,(p["id"],scene,hashes)
            unique.append(len(hashes))
        checks.append(dict(id=p["id"],mp4Frames=int(v["nb_frames"]),gifFrames=gif.n_frames,seconds=SECONDS,uniqueIntraSceneSamples=unique,mp4Sha256=hashlib.sha256((dest/"motion.mp4").read_bytes()).hexdigest(),gifSha256=hashlib.sha256((dest/"motion.gif").read_bytes()).hexdigest(),mp4Bytes=(dest/"motion.mp4").stat().st_size,gifBytes=(dest/"motion.gif").stat().st_size))
    # Independent arithmetic checks of the major derived claims.
    n,k,z=95,88,1.959963984540054
    phat=k/n
    wilson=(phat+z*z/(2*n)-z*math.sqrt(phat*(1-phat)/n+z*z/(4*n*n)))/(1+z*z/n)
    assert round(wilson*100,1)==85.6
    assert math.isclose(sum(x[1] for x in EXTRAS[4][1]),.186)
    assert math.isclose(sum(x[1] for x in EXTRAS[9][1]),.9502)
    assert round(.9502/.837,3)==1.135
    assert 80*180000/8==1800000
    if OVERFLOWS:raise AssertionError(sorted(OVERFLOWS))
    (OUT/"qa.json").write_text(json.dumps(dict(status="automated_checks_passed_visual_review_required",posts=checks,overflowCount=len(OVERFLOWS),wilsonLower95=wilson,livePostsChanged=0),indent=2)+"\n")


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--ids",nargs="*")
    parser.add_argument("--storyboards-only",action="store_true")
    parser.add_argument("--validate-only",action="store_true")
    args=parser.parse_args()
    all_posts=posts()
    chosen=[p for p in all_posts if not args.ids or p["id"] in args.ids]
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/"manifest.json").write_text(json.dumps(dict(status="prepared_not_applied",reference="https://www.linkedin.com/feed/update/urn:li:activity:7501596302342922240/",preserve=["text","links","native_mentions","hashtags","audience","comments","scheduled_time"],posts=all_posts),indent=2)+"\n")
    if args.validate_only:
        validate(chosen)
        print("Validated",len(chosen),"motion packages",flush=True)
        return
    for p in chosen:
        dest=OUT/(p["id"].lower()+"-"+p["slug"])
        dest.mkdir(parents=True,exist_ok=True)
        storyboard(p,dest)
        if not args.storyboards_only:encode(p,dest)
        print("Rendered",p["id"],p["slug"],flush=True)
    gallery(all_posts)
    if OVERFLOWS:raise AssertionError(sorted(OVERFLOWS))
    if not args.storyboards_only:validate(chosen)


if __name__=="__main__":main()
