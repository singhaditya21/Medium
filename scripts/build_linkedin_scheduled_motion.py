@lru_cache(maxsize=64)
def font(size, bold=False, mono=False):
    path = "/System/Library/Fonts/SFNSMono.ttf" if mono else "/System/Library/Fonts/Supplemental/Arial" + (" Bold" if bold else "") + ".ttf"
    return ImageFont.truetype(path, size)


@lru_cache(maxsize=8192)
def wrap(value, size, width, bold=False, mono=False):
    lines, current = [], ""
    for word in str(value).split():
        candidate = (current + " " + word).strip()
        if font(size, bold, mono).getlength(candidate) <= width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def text(d, x, y, value, size=28, color=INK, bold=False, width=960, max_lines=8, mono=False):
    lines = wrap(value, size, width, bold, mono)
    if len(lines) > max_lines:
        OVERFLOWS.add(f"lines>{max_lines}: {value}")
    for i, line in enumerate(lines):
        if x + font(size, bold, mono).getlength(line) > W - 30 or y + i * size * 1.24 + size > H - 20:
            OVERFLOWS.add(f"canvas overflow: {value}")
        d.text((x, y + i * size * 1.24), line, font=font(size, bold, mono), fill=color)
    return y + len(lines) * size * 1.24


def center(d, x, y, value, size=26, color=INK, bold=False):
    d.text((x, y), str(value), font=font(size, bold), fill=color, anchor="mm")


def smooth(p):
    p = max(0., min(1., p))
    return p * p * (3 - 2 * p)


def box(d, coords, fill=WHITE, outline=LINE, width=2):
    d.rounded_rectangle(coords, radius=20, fill=fill, outline=outline, width=width)


def arrow(d, a, b, t, dashed=False):
    if dashed:
        for i in range(0, 20, 2):
            u, v = i / 20, (i + 1) / 20
            d.line((a[0] + (b[0]-a[0])*u, a[1] + (b[1]-a[1])*u,
                    a[0] + (b[0]-a[0])*v, a[1] + (b[1]-a[1])*v), fill=INK, width=3)
    else:
        d.line((*a, *b), fill=BLUE, width=3)
    angle = math.atan2(b[1] - a[1], b[0] - a[0])
    d.polygon([b, (b[0]-12*math.cos(angle-.5), b[1]-12*math.sin(angle-.5)),
               (b[0]-12*math.cos(angle+.5), b[1]-12*math.sin(angle+.5))], fill=INK if dashed else BLUE)
    p = t % 1
    x, y = a[0] + (b[0]-a[0])*p, a[1] + (b[1]-a[1])*p
    d.ellipse((x-7,y-7,x+7,y+7), fill=BLUE)


